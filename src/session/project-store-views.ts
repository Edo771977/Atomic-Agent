import { basename } from "node:path";
import { criterionFactLine } from "./project-gate-text.js";
import { backlogSourceLabel, backlogStateOf } from "./project-backlog.js";
import { projectExpectation, type ProjectExpectation, type ProjectState } from "./session-project.js";

/**
 * The readable views of a fusion project's store (issue #109):
 * `BRIEF.md`, `PLAN.md` and `STATUS.md`, generated from the resolved
 * project after every write and never read back. Each starts with a
 * line saying so; editing them changes nothing.
 */

const HEADER = "<!-- Generated by Atomic Agent from project.json; edits here are overwritten and never read. -->";

/** What a view needs of the stored project. */
export interface ProjectViewSource {
  name: string;
  updatedAt: number;
}

/** One line for what happens next ({@link projectExpectation}). */
export function describeExpectation(expectation: ProjectExpectation): string {
  switch (expectation.kind) {
    case "draft_brief":
      return "the director drafts the brief";
    case "draft_plan":
      return "the director drafts the plan";
    case "run_milestone":
      return `the director runs milestone ${expectation.id}`;
    case "await_person":
      return expectation.gate.kind === "milestone"
        ? `you review milestone ${expectation.gate.id}`
        : `you approve the ${expectation.gate.kind}`;
    case "complete":
      return ["nothing: every milestone is reviewed", ...completeWith(expectation)].join("; ");
    case "cancelled":
      return "nothing: the project was cancelled";
  }
}

/** The gate as a short label: `brief`, `plan`, `milestone <id>`, `none`. */
export function gateLabel(project: ProjectState): string {
  return project.gate.kind === "milestone" ? `milestone ${project.gate.id}` : project.gate.kind;
}

export function renderProjectViews(source: ProjectViewSource, project: ProjectState): Record<"BRIEF.md" | "PLAN.md" | "STATUS.md", string> {
  const brief = project.brief;
  const briefLines = [HEADER, "", `# ${source.name}: brief`, ""];
  if (brief === undefined) briefLines.push("No brief yet.");
  else {
    briefLines.push(
      `Version ${brief.version}, ${brief.status}.`,
      "",
      "## What",
      "",
      brief.what,
      "",
      "## For",
      "",
      brief.users,
      "",
      "## How",
      "",
      brief.how,
      "",
      "## Done when",
      "",
      ...(brief.successCriteria.length === 0 ? ["(no criteria)"] : brief.successCriteria.map((c) => `- \`${c.id}\` ${c.text}`)),
    );
    if (brief.deliverable !== undefined) briefLines.push("", `Deliverable: ${brief.deliverable}`);
    if ((brief.decisions ?? []).length > 0) {
      briefLines.push("", "## Decisions", "", ...brief.decisions!.map((d) => `- \`${d.id}\` ${d.text} (${project.decisionStatus?.[d.id] ?? "active"})`));
    }
  }
  if ((project.backlog ?? []).length > 0) {
    briefLines.push("", "## Backlog", "", ...project.backlog!.map((b) => `- \`${b.id}\` ${b.title}${b.condition === undefined ? "" : ` (when: ${b.condition})`}: ${backlogStateOf(project, b.id)}, from ${backlogSourceLabel(b)}`));
  }

  const plan = project.plan;
  const planLines = [HEADER, "", `# ${source.name}: plan`, ""];
  if (plan === undefined) planLines.push("No plan yet.");
  else {
    planLines.push(`Version ${plan.version}, ${plan.status}.`, "");
    for (const m of project.milestones) {
      planLines.push(`## ${m.title} (\`${m.id}\`, ${m.kind})`, "");
      const rows = plan.rows.filter((r) => r.milestoneId === m.id);
      if (rows.length === 0) planLines.push("(no tasks)");
      for (const r of rows) {
        // Issue #146: the backlog items the task takes in.
        const backlog = (r.backlog ?? []).length === 0 ? "" : `; backlog: ${r.backlog!.join(", ")}`;
        planLines.push(`- \`${r.taskId}\` ${r.title}: ${r.worker}${r.reviewer === null ? "" : `, reviewed by ${r.reviewer}`}${backlog}`);
      }
      planLines.push("");
    }
  }

  const statusLines = [
    HEADER,
    "",
    `# ${source.name}: status`,
    "",
    `Waiting on: ${gateLabel(project)}`,
    `Next: ${describeExpectation(projectExpectation(project))}`,
    `Updated: ${new Date(source.updatedAt).toISOString()}`,
    ...(project.changedOutside === undefined ? [] : [`Changed since your decision: ${project.changedOutside.join(", ")}`]),
    "",
  ];
  for (const m of project.milestones) {
    statusLines.push(`## ${m.title}: ${m.state}`, "");
    if (m.summary !== undefined) statusLines.push(m.summary, "");
    for (const fact of m.criteriaFacts ?? []) statusLines.push(`- ${criterionFactLine(fact, brief?.successCriteria)}`);
    for (const a of m.attachments ?? []) statusLines.push(`- picture: ${a.caption} (${basename(a.path)})`);
    if ((m.criteriaFacts ?? []).length > 0 || (m.attachments ?? []).length > 0) statusLines.push("");
  }
  const text = (lines: string[]) => `${lines.join("\n").trimEnd()}\n`;
  return { "BRIEF.md": text(briefLines), "PLAN.md": text(planLines), "STATUS.md": text(statusLines) };
}

/** What a complete project still leaves (issues #111, #146): open items, and promoted items no run took in. */
export function completeWith(expectation: { openBacklog?: number; promotedNotDone?: number }): string[] {
  const n = (count: number, what: string) => `${count} ${what}${count === 1 ? "" : "s"}`;
  return [
    ...(expectation.openBacklog === undefined ? [] : [`complete with ${n(expectation.openBacklog, "backlog item")} still open`]),
    ...(expectation.promotedNotDone === undefined ? [] : [`complete with ${n(expectation.promotedNotDone, "promoted backlog item")} not done`]),
  ];
}
